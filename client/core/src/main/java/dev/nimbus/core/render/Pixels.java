package dev.nimbus.core.render;

import dev.nimbus.bridge.GameBridge;

/**
 * Переход к рисованию в настоящих пикселях экрана.
 *
 * Игра рисует интерфейс увеличенным: при масштабе 3 одна его единица - это
 * квадрат 3x3 настоящих пикселей. Любое скругление, посчитанное в таких
 * единицах, неизбежно выглядит крупнозернистым: сглаживать нечего, меньше
 * единицы шага нет.
 *
 * Решение: уменьшить единицу рисования в scale раз и во столько же увеличить
 * все координаты. Панель остаётся того же размера на экране, но дуга считается
 * по настоящим пикселям, и сглаживание наконец видно.
 *
 * Текст так рисовать не надо: шрифт игры рассчитан на единицы интерфейса и в
 * мелком масштабе превратится в нечитаемую кашу.
 */
public final class Pixels {

    /** Дальше увеличивать точность бессмысленно, а цена растёт квадратично. */
    private static final int MAX = 6;

    private Pixels() {
    }

    /** Сколько настоящих пикселей в одной единице интерфейса. */
    public static int scale(GameBridge game) {
        double value = game.guiScale();
        if (!(value > 1.0)) {
            return 1;
        }
        return (int) Math.min(MAX, Math.round(value));
    }
}
