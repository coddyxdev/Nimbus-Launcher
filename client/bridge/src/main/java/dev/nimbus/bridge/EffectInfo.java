package dev.nimbus.bridge;

/**
 * Один активный эффект игрока, снятый с игры и сложенный в простую форму.
 *
 * Снимок делается адаптером редко и только при изменениях, поэтому ядро может
 * читать эффекты каждый кадр без единой аллокации: массив снимков живёт в мосте.
 *
 * @param name      человеческое название эффекта ("Скорость", "Сила")
 * @param amplifier уровень эффекта, начиная с нуля (ноль - уровень I)
 * @param seconds   сколько секунд осталось; -1 для бесконечных эффектов
 * @param harmful   правда, если эффект вредит игроку
 */
public record EffectInfo(String name, int amplifier, int seconds, boolean harmful) {
}
