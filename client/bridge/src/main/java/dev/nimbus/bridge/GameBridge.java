package dev.nimbus.bridge;

/**
 * Единственная дверь из клиента в игру.
 *
 * Чем уже этот интерфейс, тем дешевле поддержка каждой новой версии Minecraft:
 * реализация живёт в adapters, вся логика - в core.
 *
 * Здесь только сырые операции, которые умеет сама игра. Всё, что можно сложить
 * из них (скруглённые углы, панели, меню), считается в core и одинаково работает на
 * всех версиях.
 *
 * Цвет везде - целое число ARGB (0xAARRGGBB). Координаты везде - в единицах
 * игрового интерфейса, если не включён мелкий масштаб через {@link #pushScale(float)}.
 */
public interface GameBridge {

    /** Версия запущенной игры, например 1.20.1. */
    String gameVersion();

    /**
     * Готов ли мост рисовать.
     *
     * Если хоть одно имя не нашлось, мост выключает себя целиком и все его вызовы
     * становятся пустыми: игра должна идти дальше даже без нашего интерфейса.
     */
    boolean ready();

    /**
     * Начало кадра: мост запоминает контекст рисования игры.
     *
     * Вне пары beginFrame/endFrame рисовать нельзя: контекст действителен только
     * внутри одного кадра.
     */
    void beginFrame(Object graphics, float partialTick);

    /** Конец кадра: контекст забывается, ссылка на игру не удерживается. */
    void endFrame();

    /** Доля тика текущего кадра: нужна анимациям для плавности. */
    float partialTick();

    /** Ширина экрана в единицах интерфейса. */
    int screenWidth();

    /** Высота экрана в единицах интерфейса. */
    int screenHeight();

    /** Масштаб интерфейса игры. */
    double guiScale();

    /**
     * Уменьшить единицу рисования до физического пикселя экрана.
     *
     * При масштабе интерфейса 2 одна его единица - это квадрат 2x2 настоящих
     * пикселей, поэтому скругления выглядят крупнозернистыми. Внутри pushScale
     * координаты считаются в настоящих пикселях. Обязательно закрыть через {@link #popScale()}.
     */
    void pushScale(float scale);

    /** Вернуть прежний масштаб рисования. */
    void popScale();

    /** Захвачен ли курсор игрой. */
    boolean cursorGrabbed();

    /** Отпустить или захватить курсор - нужно для меню. */
    void setCursorGrabbed(boolean grabbed);

    /** Нажата ли клавиша прямо сейчас. Код клавиши - по {@link Keys}. */
    boolean keyDown(int key);

    /** Положение курсора по горизонтали в единицах интерфейса. */
    int mouseX();

    /** Положение курсора по вертикали в единицах интерфейса. */
    int mouseY();

    /**
     * Точное положение курсора по горизонтали с долями единицы.
     *
     * При масштабе интерфейса 3 целое значение меняется раз в три настоящих пикселя,
     * и перетаскивание окна идёт заметными ступеньками. Для плавности нужно дробное.
     */
    double mouseXPrecise();

    /** Точное положение курсора по вертикали с долями единицы. */
    double mouseYPrecise();

    /** Нажата ли кнопка мыши: 0 - левая, 1 - правая. */
    boolean mouseDown(int button);

    /**
     * Забрать накопленную прокрутку колеса и обнулить счётчик.
     *
     * Положительное значение - колесо от себя (вверх). Событие ловит рантайм в игре:
     * у оконной библиотеки спросить "сколько накрутили" нельзя.
     */
    double takeScroll();

    /** Залить прямоугольник сплошным цветом. */
    void fill(int x, int y, int width, int height, int argb);

    /** Залить прямоугольник вертикальным градиентом. */
    void fillGradient(int x, int y, int width, int height, int topArgb, int bottomArgb);

    /** Написать текст шрифтом игры. Возвращает координату после последнего символа. */
    int drawText(String text, int x, int y, int argb, boolean shadow);

    /** Ширина строки шрифтом игры. */
    int textWidth(String text);

    /** Высота строки шрифтом игры. */
    int textHeight();

    /** Ограничить рисование прямоугольником. Обязательно закрыть через scissorOff. */
    void scissorOn(int x, int y, int width, int height);

    /** Снять ограничение рисования. */
    void scissorOff();

    /** Игрок в мире: в главном меню телеметрии нет. */
    boolean inWorld();

    /** Координата игрока по X. */
    double playerX();

    /** Координата игрока по Y. */
    double playerY();

    /** Координата игрока по Z. */
    double playerZ();

    /** Поворот камеры по горизонтали в градусах. */
    float playerYaw();

    /** Задержка до сервера в миллисекундах. -1, если неизвестна. */
    int ping();

    /**
     * Проиграть звук интерфейса. Код звука - по {@link Sounds}.
     *
     * Высота тона - множитель от 0.5 до 2.0: именно им ванильный звук
     * превращается в свой.
     */
    void playSound(int sound, float pitch);

    /** Сообщение в игровой чат (только локально, на сервер не уходит). */
    void printMessage(String text);
}
