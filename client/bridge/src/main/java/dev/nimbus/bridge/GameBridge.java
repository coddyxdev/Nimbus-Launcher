package dev.nimbus.bridge;

/**
 * Единственная дверь из клиента в игру.
 *
 * Чем уже этот интерфейс, тем дешевле поддержка каждой новой версии Minecraft:
 * реализация живёт в adapters, вся логика - в core.
 *
 * Здесь только сырые операции, которые умеет сама игра. Всё, что можно сложить
 * из них (скруглённые углы, тени, панели), считается в core и одинаково работает
 * на всех версиях.
 *
 * Цвет везде - целое число ARGB (0xAARRGGBB). Координаты везде - в единицах
 * игрового интерфейса, а не в пикселях экрана.
 */
public interface GameBridge {

    /** Версия запущенной игры, например 1.20.1. */
    String gameVersion();

    /**
     * Готов ли мост рисовать.
     *
     * Если хоть одно имя не нашлось, мост выключает себя целиком и все его вызовы
     * становятся пустыми: игра должна идти дальше даже без нашего интерфейса.
     */
    boolean ready();

    /**
     * Начало кадра: мост запоминает контекст рисования игры.
     *
     * Вне пары beginFrame/endFrame рисовать нельзя: контекст действителен только
     * внутри одного кадра.
     */
    void beginFrame(Object graphics, float partialTick);

    /** Конец кадра: контекст забывается, ссылка на игру не удерживается. */
    void endFrame();

    /** Доля тика текущего кадра: нужна анимациям для плавности. */
    float partialTick();

    /** Ширина экрана в единицах интерфейса. */
    int screenWidth();

    /** Высота экрана в единицах интерфейса. */
    int screenHeight();

    /** Масштаб интерфейса игры. */
    double guiScale();

    /** Захвачен ли курсор игрой. */
    boolean cursorGrabbed();

    /** Отпустить или захватить курсор - нужно для меню по правому Shift. */
    void setCursorGrabbed(boolean grabbed);

    /** Залить прямоугольник сплошным цветом. */
    void fill(int x, int y, int width, int height, int argb);

    /** Залить прямоугольник вертикальным градиентом. */
    void fillGradient(int x, int y, int width, int height, int topArgb, int bottomArgb);

    /** Написать текст шрифтом игры. Возвращает координату после последнего символа. */
    int drawText(String text, int x, int y, int argb, boolean shadow);

    /** Ширина строки шрифтом игры. */
    int textWidth(String text);

    /** Высота строки шрифтом игры. */
    int textHeight();

    /** Ограничить рисование прямоугольником. Обязательно закрыть через scissorOff. */
    void scissorOn(int x, int y, int width, int height);

    /** Снять ограничение рисования. */
    void scissorOff();

    /** Сообщение в игровой чат (только локально, на сервер не уходит). */
    void printMessage(String text);
}
